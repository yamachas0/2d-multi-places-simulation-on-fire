def parse_persona(text: str, axis_id: str, a1: str, a2: str, a3: str, variant: str) -> dict:
    """Parse the variant-specific response into a persona dict."""
    fields = {}
    for line in text.splitlines():
        m = re.match(r"^\s*([^:：]+)[:：]\s*(.+)$", line)
        if not m: continue
        key = m.group(1).strip()
        val = m.group(2).strip()
        if "名前" in key: fields["name"] = val
        elif "性別" in key: fields["gender"] = val
        elif "年齢" in key: fields["age"] = val
        elif "学年" in key: fields["grade"] = val
        elif "家族" in key: fields["family_struct"] = val
        elif "得意" in key or "苦手" in key and variant == "high": fields["subjects"] = val
        elif "部活" in key: fields["club"] = val
        elif "本業" in key: fields["occupation"] = val
        elif "シンギュラボ" in key or "参加経緯" in key: fields["join_reason"] = val
        elif "好きなこと" in key: fields["hobby_like"] = val
        elif "苦手なこと" in key: fields["hobby_dislike"] = val
        elif "将来" in key or "関心" in key: fields["future_interest"] = val
        elif "気になって" in key: fields["recent_concern"] = val
        elif "口癖" in key: fields["catchphrase"] = val
        elif "スマホ" in key: fields["phone_habit"] = val

    g = fields.get("gender", "").lower().strip()
    if "女" in g or "female" in g: fields["gender"] = "female"
    elif "男" in g or g == "male": fields["gender"] = "male"
    else: fields["gender"] = "other"

    fields["axis_id"] = axis_id
    fields["axis_career"] = a1   # 高校:進路 / 社会人:専門領域 / 小学生:学習姿勢 / 中学生:進路
    fields["axis_friends"] = a2  # 高校:友人 / 社会人:コミュ関与 / 小学生:友達 / 中学生:友人
    fields["axis_family"] = a3   # 高校:家庭 / 社会人:挑戦経験 / 小学生:家庭 / 中学生:家庭
    fields["variant"] = variant
    return fields


